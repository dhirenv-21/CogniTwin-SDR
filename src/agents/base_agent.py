"""
Base Intelligence Agent Abstract Class.

Provides shared structure, confidence tracking, and status monitoring for all specialized agents.
"""

from abc import ABC, abstractmethod
from typing import Any, Optional


class BaseAgent(ABC):
    """
    Abstract base class for all Cognitive Wireless Intelligence Agents.
    """

    def __init__(self, name: str):
        self.name = name
        self.confidence: float = 1.0
        self.status: str = "IDLE"
        self._last_output: Optional[Any] = None

    @abstractmethod
    def process(self, *args, **kwargs) -> Any:
        """Processes input evidence and returns structured message output."""
        pass

    def get_last_output(self) -> Optional[Any]:
        """Returns the most recent output generated by this agent."""
        return self._last_output
